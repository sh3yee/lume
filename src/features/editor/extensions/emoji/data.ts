export const emojiEntries: readonly EmojiEntry[] = Object.entries(emojiAliases).map(
  ([name, emoji]) => ({ name, emoji }),
)

export const findEmoji = (name: string): string | undefined =>
  Object.prototype.hasOwnProperty.call(emojiAliases, name) ? emojiAliases[name] : undefined

export const searchEmoji = (query: string, limit = 8): EmojiEntry[] => {
  const name = query.toLowerCase()
  const matches = emojiEntries.filter((entry) => entry.name.includes(name))
  return matches
    .sort((a, b) => Number(b.name.startsWith(name)) - Number(a.name.startsWith(name)))
    .slice(0, Math.max(0, limit))
}
